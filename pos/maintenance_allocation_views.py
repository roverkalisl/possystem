@user_passes_test(can_use_project)
def maintenance_allocation_available(request):
    """JSON helper for the form: live available cost for a project and month."""
    project = Project.objects.filter(id=request.GET.get("project") or 0).first()
    month = parse_month(request.GET.get("month"))
    if not project or not month:
        return JsonResponse({"available": None})
    return JsonResponse({"available": str(available_cost(project, month))})


@user_passes_test(can_use_project)
def maintenance_allocation_detail(request, pk):
    alloc = get_object_or_404(
        MaintenanceAllocation.objects.select_related(
            "source_project", "created_by", "submitted_by", "approved_by",
            "rejected_by", "posted_by", "reversed_by",
        ), pk=pk,
    )
    live = alloc.status not in ("posted", "reversed")
    available = available_cost(alloc.source_project, alloc.month) if live else alloc.available_amount
    allocated = allocated_total(alloc)
    remaining = q2(available) - allocated
    owner = is_owner(request.user)
    return render(request, "pos/maintenance_allocation_detail.html", {
        "allocation": alloc,
        "lines": alloc.lines.select_related("project", "gl_account"),
        "entries": alloc.project_expense_entries.select_related("project", "gl_account").order_by("id"),
        "available": q2(available),
        "allocated": allocated,
        "remaining": remaining,
        "balanced": remaining == ZERO,
        "month_closing": closing_balance(alloc.source_project, alloc.month),
        "is_owner": owner,
        "can_edit": alloc.status in EDITABLE_STATUSES,
        "can_submit": alloc.status in EDITABLE_STATUSES and alloc.lines.exists(),
        "can_approve": owner and alloc.status == "pending",
        "can_reject": owner and alloc.status in ("pending", "approved"),
        "can_post": owner and alloc.status == "approved",
        "can_reverse": owner and alloc.status == "posted",
    })


def _run_action(request, pk, func, success, *extra):
    try:
        func(request.user, pk, *extra)
        messages.success(request, success)
    except AllocationError as exc:
        messages.error(request, str(exc))
    return redirect("maintenance_allocation_detail", pk=pk)


