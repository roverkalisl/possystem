@user_passes_test(can_use_project)
def maintenance_allocation_report(request):
    lines = MaintenanceAllocationLine.objects.select_related(
        "allocation", "allocation__source_project", "allocation__created_by",
        "allocation__approved_by", "project",
    ).order_by("-allocation__month", "allocation__reference", "id")

    month = request.GET.get("month") or ""
    source = request.GET.get("source_project") or ""
    dest = request.GET.get("destination_project") or ""
    status = request.GET.get("status") or ""
    reference = (request.GET.get("reference") or "").strip()
    if month and parse_month(month):
        lines = lines.filter(allocation__month=parse_month(month))
    if source:
        lines = lines.filter(allocation__source_project_id=source)
    if dest:
        lines = lines.filter(project_id=dest)
    if status:
        lines = lines.filter(allocation__status=status)
    if reference:
        lines = lines.filter(allocation__reference__icontains=reference)

    lines = list(lines)
    posted_lines = [l for l in lines if l.allocation.status == "posted"]
    posted_allocs = {l.allocation_id: l.allocation for l in posted_lines}
    total_available = sum((a.available_amount for a in posted_allocs.values()), ZERO)
    total_allocated = sum((l.amount for l in posted_lines), ZERO)
    # Live balance of each posted month: non-zero means cost was entered for that
    # month after posting (late entry). It is reported, never silently re-allocated.
    late_variances = []
    live_closing = ZERO
    for a in posted_allocs.values():
        bal = closing_balance(a.source_project, a.month)
        live_closing += bal
        if bal != ZERO:
            late_variances.append({"allocation": a, "balance": bal})

    return render(request, "pos/maintenance_allocation_report.html", {
        "lines": lines,
        "total_available": total_available,
        "total_allocated": total_allocated,
        "closing_balance": live_closing,
        "late_variances": late_variances,
        "projects": Project.objects.order_by("project_id"),
        "status_choices": MaintenanceAllocation.STATUS_CHOICES,
        "f": {"month": month, "source_project": source, "destination_project": dest,
              "status": status, "reference": reference},
    })
